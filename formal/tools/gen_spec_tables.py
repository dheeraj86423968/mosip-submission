#!/usr/bin/env python3
"""Generate GeneratedSpecTables.java from the TLA+ spec and TLC state-graph dumps.

The output is a checked artifact (PLAN.md 17.7): the phase enum, failure reasons and action names of
formal/LivenessOrchestrator.tla, plus the phase-level transition table ("FROM -Action-> TO") that TLC
explored for every configuration.  SpecConformanceTest asserts that the Java API matches the enums and
that every transition the real orchestrator takes during trace replay is in the table; CI regenerates
the file and fails if it differs from the committed copy.

usage: gen_spec_tables.py SPEC.tla OUT.java DUMP.dot [DUMP.dot ...]
"""
import re
import sys

NODE = re.compile(r'^(-?\d+) \[label="(.*)"(?:,style = filled)?\];?$')
EDGE = re.compile(r'^(-?\d+) -> (-?\d+) \[label="([^"]*)"')


def set_literal(spec, name):
    m = re.search(name + r'\s*==\s*\{(.*?)\}', spec, re.S)
    if not m:
        raise SystemExit('no set literal for ' + name)
    return re.findall(r'"([A-Z_]+)"', m.group(1))


def disjuncts(spec, name):
    m = re.search(r'^' + name + r'\s*==(.*?)\n(?=\S)', spec, re.S | re.M)
    if not m:
        raise SystemExit('no definition for ' + name)
    return [t.strip() for t in re.split(r'\\/', m.group(1)) if t.strip()]


def phase_of(label):
    m = re.search(r'phase = \\"([A-Z_]+)\\"', label)
    return m.group(1)


def main():
    spec_path, out_path, dumps = sys.argv[1], sys.argv[2], sys.argv[3:]
    spec = open(spec_path, encoding='utf-8').read()
    phases = set_literal(spec, 'Phases')
    terminal = set_literal(spec, 'TerminalPhases')
    reasons = []
    for group in ('DeviceReasons', 'AcquireReasons', 'EngineReasons'):
        reasons += set_literal(spec, group)
    m = re.search(r'Reasons == .*?\{(.*?)\}', spec[spec.index('Reasons == DeviceReasons'):], re.S)
    reasons += re.findall(r'"([A-Z_]+)"', m.group(1))
    actions = []
    for kind, name in (('CLIENT', 'ClientNext'), ('ENVIRONMENT', 'EnvNext'), ('ORCHESTRATOR', 'CoreNext')):
        actions += [(a, kind) for a in disjuncts(spec, name)]

    transitions = set()
    for dump in dumps:
        phase_by_id = {}
        edges = []
        with open(dump, encoding='utf-8') as f:
            for line in f:
                line = line.rstrip('\n')
                e = EDGE.match(line)
                if e:
                    edges.append(e.groups())
                    continue
                n = NODE.match(line)
                if n:
                    phase_by_id[n.group(1)] = phase_of(n.group(2))
        for src, dst, label in edges:
            if src != dst:
                transitions.add('%s -%s-> %s' % (phase_by_id[src], label, phase_by_id[dst]))

    q = lambda xs: ',\n            '.join('"%s"' % x for x in xs)
    out = []
    out.append('// GENERATED by formal/tools/gen_spec_tables.py from formal/LivenessOrchestrator.tla and the TLC')
    out.append('// state graphs of its configurations. DO NOT EDIT: run formal/conformance.sh to regenerate.')
    out.append('package io.mosip.vivid.core.session;')
    out.append('')
    out.append('import java.util.List;')
    out.append('import java.util.Set;')
    out.append('')
    out.append('/** Tables generated from the verified TLA+ model of the session orchestrator (PLAN.md section 17.7). */')
    out.append('final class GeneratedSpecTables {')
    out.append('')
    out.append('    private GeneratedSpecTables() {}')
    out.append('')
    out.append('    /** {@code Phases} of the spec, in declaration order; must equal {@code SessionState.Phase}. */')
    out.append('    enum SpecPhase { %s }' % ', '.join(phases))
    out.append('')
    out.append('    /** Who takes a spec action. */')
    out.append('    enum Actor { CLIENT, ENVIRONMENT, ORCHESTRATOR }')
    out.append('')
    out.append('    /** Disjuncts of {@code ClientNext}, {@code EnvNext} and {@code CoreNext}. */')
    out.append('    enum SpecAction {')
    out.append(',\n'.join('        %s(Actor.%s)' % a for a in actions) + ';')
    out.append('')
    out.append('        final Actor actor;')
    out.append('')
    out.append('        SpecAction(Actor actor) {')
    out.append('            this.actor = actor;')
    out.append('        }')
    out.append('    }')
    out.append('')
    out.append('    /** {@code TerminalPhases}. */')
    out.append('    static final Set<String> TERMINAL_PHASES = Set.of(%s);' % ', '.join('"%s"' % t for t in terminal))
    out.append('')
    out.append('    /** {@code Reasons} (with {@code NONE} for "no failure recorded"). */')
    out.append('    static final List<String> FAILURE_REASONS = List.of(\n            %s);' % q(reasons))
    out.append('')
    out.append('    /** Every phase-level transition "FROM -Action-> TO" in the TLC state graphs ({@value #TRANSITION_COUNT} entries). */')
    out.append('    static final Set<String> PHASE_TRANSITIONS = Set.of(\n            %s);' % q(sorted(transitions)))
    out.append('')
    out.append('    static final int TRANSITION_COUNT = %d;' % len(transitions))
    out.append('}')
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote %s: %d phases, %d actions, %d reasons, %d phase transitions' % (out_path, len(phases), len(actions), len(reasons), len(transitions)))


if __name__ == '__main__':
    main()
